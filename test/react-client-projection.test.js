test('verifyReactClientProjection separates artifact drift from a wrong file set', async () => {
  const { manifest, workspace } = contract()
  const out = join(workspace, 'verified')
  const written = await writeReactClientProjection(manifest, { output: out })
  assert.equal(written.ok, true)

  const clean = await verifyReactClientProjection(manifest, { output: out })
  assert.equal(clean.ok, true)

  writeFileSync(join(out, 'panels.tsx'), '// drifted\n')
  const drift = await verifyReactClientProjection(manifest, { output: out })
  assert.equal(drift.ok, false)
  assert.equal(drift.diagnostics[0].code, 'projection-artifact-drift')
  assert.equal(drift.diagnostics[0].path, 'panels.tsx')

  const extra = join(workspace, 'extra')
  await writeReactClientProjection(manifest, { output: extra })
  writeFileSync(join(extra, 'stray.ts'), 'export {}\n')
  const stray = await verifyReactClientProjection(manifest, { output: extra })
  assert.equal(stray.ok, false)
  assert.equal(stray.diagnostics[0].code, 'projection-artifact-file-set-drift')

  const absent = await verifyReactClientProjection(manifest, { output: join(workspace, 'none') })
  assert.equal(absent.ok, false)
  assert.equal(absent.diagnostics[0].code, 'projection-artifact-missing')
  rmSync(workspace, { force: true, recursive: true })
})

