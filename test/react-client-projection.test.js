const repositoryRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const cli = resolve(repositoryRoot, 'src/cli/re.js')
const project = resolve(repositoryRoot, 'examples/agent-expense-review')
const routes = resolve(project, 'interface-routes.json')

function run(arguments_, options = {}) {
  return spawnSync(process.execPath, [cli, ...arguments_], { encoding: 'utf8', ...options })
}

function contract() {
  const workspace = mkdtempSync(join(tmpdir(), 'revia-react-contract-'))
  const out = join(workspace, 'projection')
  const projected = run(['project-projection', '--routes', routes, '--out', out, project])
  assert.equal(projected.status, 0, projected.stderr)
  return {
    manifest: JSON.parse(readFileSync(join(out, 'projection.json'), 'utf8')),
    out,
    workspace,
  }
}

test('project-react turns a checked projection contract into client artifacts', () => {
  const { manifest, workspace } = contract()
  const out = join(workspace, 'react')
  const generated = run(['project-react', '--contract', join(workspace, 'projection/projection.json'), '--out', out])
  assert.equal(generated.status, 0, generated.stderr)

  const envelope = JSON.parse(generated.stdout)
  assert.equal(envelope.schema, 're.react-client-projection-result@0.1.0')
  assert.equal(envelope.ok, true)
  assert.equal(envelope.written, true)
  assert.equal(envelope.manifest.schema, 're.react-client-projection-manifest@0.1.0')
  assert.equal(envelope.manifest.authority.projection_digest, manifest.projection_digest)
  assert.equal(
    envelope.manifest.authority.graph_revision,
    manifest.contract.authority.graph_revision,
  )
  assert.deepEqual(
    envelope.manifest.files.map(({ path }) => path),
    ['operations.ts', 'panels.tsx'],
  )

  const operations = readFileSync(join(out, 'operations.ts'), 'utf8')
  assert.match(operations, /^\/\/ Generated by Revia React client projection\./)
  assert.match(operations, /import type \{ ProjectionClient \} from '\.\/client\.js'/)
  assert.match(operations, /export type ReviewState =/)
  assert.match(operations, /export function useReview\(/)

  const panels = readFileSync(join(out, 'panels.tsx'), 'utf8')
  assert.match(panels, /export function ReviewPanel\(/)
  assert.match(panels, /<button type="submit" disabled=\{state\.status === 'pending'\}>/)
  assert.match(panels, /return <p role="alert">\{state\.error\.variant\}<\/p>/)
  // Every name panels.tsx uses from operations.ts is imported, the state type
  // included: the panel annotates its outcome component with it.
  assert.match(
    panels,
    /import \{ useReview, type ReviewState \} from '\.\/operations\.js'/,
  )

  // The generator reads the contract and writes nothing back into it.
  assert.deepEqual(
    JSON.parse(readFileSync(join(workspace, 'projection/projection.json'), 'utf8')),
    manifest,
  )
  rmSync(workspace, { force: true, recursive: true })
})

test('project-react is deterministic across fresh processes', () => {
  const { workspace } = contract()
  const contractFile = join(workspace, 'projection/projection.json')
  const left = join(workspace, 'left')
  const right = join(workspace, 'right')
  const first = run(['project-react', '--contract', contractFile, '--out', left])
  const second = run(['project-react', '--contract', contractFile, '--out', right])
  assert.equal(first.status, 0, first.stderr)
  assert.equal(second.status, 0, second.stderr)
  assert.equal(first.stdout, second.stdout)
  for (const path of ['operations.ts', 'panels.tsx', 'react-client.json']) {
    assert.equal(
      readFileSync(join(left, path), 'utf8'),
      readFileSync(join(right, path), 'utf8'),
      path,
    )
  }
  rmSync(workspace, { force: true, recursive: true })
})

test('project-react refuses a contract whose digest no longer matches its bytes', async () => {
  const { manifest, workspace } = contract()
  const tampered = {
    ...manifest,
    contract: {
      ...manifest.contract,
      operations: manifest.contract.operations.map((operation) => ({ ...operation })),
    },
    projection_digest: `sha256:${'0'.repeat(64)}`,
  }
  const contractFile = join(workspace, 'tampered.json')
  writeFileSync(contractFile, JSON.stringify(tampered))
  const out = join(workspace, 'refused')

  const result = run(['project-react', '--contract', contractFile, '--out', out])
  assert.equal(result.status, 65)
  const envelope = JSON.parse(result.stdout)
  assert.equal(envelope.ok, false)
  assert.equal(envelope.written, false)
  assert.deepEqual(
    envelope.diagnostics.map(({ code }) => code),
    ['react-projection-contract-digest-mismatch'],
  )
  assert.equal(existsSync(out), false)

  const built = buildReactClientProjection(tampered)
  assert.equal(built.ok, false)
  assert.equal(built.diagnostics[0].code, 'react-projection-contract-digest-mismatch')
  rmSync(workspace, { force: true, recursive: true })
})

